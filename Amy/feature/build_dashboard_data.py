#!/usr/bin/env python3
"""Build the presentation-ready Blind Spot Investigator data file for the dashboard.

Reads (never writes) the validated records in output/watson_miss_explanations.json and the
evidence in output/explanation_evidence.json, and writes output/dashboard_investigations.json:
only the fields an analyst needs, with evidence anchors resolved to readable labels. Provenance
(source, model_id, revision notes, original watsonx.ai drafts) stays in the validated records;
the dashboard file keeps a separate provenance map and a record_key + SHA-256 link per item.

No AI calls. Run after watson_explain_misses.py --recheck:
    python Amy/feature/build_dashboard_data.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from datetime import datetime, timezone

sys.dont_write_bytecode = True
import watson_explain_misses as w  # noqa: E402

DASHBOARD_PATH = w.OUT / "dashboard_investigations.json"
SOURCE_LABELS = {
    "ibm_watsonx_ai": "Generated by IBM watsonx.ai",
    "cursor_generated": "Generated offline by the Cursor agent (not IBM watsonx.ai)",
    "cursor_revised_watsonx_draft": "IBM watsonx.ai draft, corrected offline by the Cursor agent",
}
DISPLAY_VOTERS = {"logistic_regression": "Logistic regression", "granite_lora": "Granite LoRA", "lightgbm": "LightGBM"}


def record_hash(record: dict) -> str:
    return hashlib.sha256(json.dumps(record, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


def label_anchors(anchors: list[str], labels: dict[str, str]) -> list[dict]:
    return [{"key": a, "label": labels.get(a, a)} for a in anchors]


def explanations(ai: dict, labels: dict[str, str]) -> list[dict]:
    return [{"hypothesis": h["hypothesis"], "category": h["category"], "confidence": h["confidence"],
             "evidence": label_anchors(h.get("evidence_anchors") or [], labels), "how_to_check": h["how_to_check"]}
            for h in ai["possible_explanations"]]


def takeaways(ai: dict, labels: dict[str, str]) -> list[dict]:
    return [{"warning_sign": l["warning_sign_or_gap"], "what_to_investigate": l["what_to_investigate"],
             "why_it_applies": l["why_it_applies_here"], "limitation": l["limits"],
             "evidence": label_anchors(l.get("evidence_anchors") or [], labels)}
            for l in ai["analyst_lessons"]]


def case_item(record: dict, case: dict, labels: dict[str, str]) -> dict:
    ai, vf = record["ai_generated"], record["verified_findings"]
    r, nvd = case["ranking"], case["retrospective_nvd_context"]
    reading = case["granite_description_reading"] or {}
    outcome = case["outcome_not_a_model_input"]
    attribution = case["linear_model_attribution"]
    voters = r["voter_ranks"]
    best = min(voters, key=voters.get)
    return {
        "id": case["cve_id"],
        "record_key": case["cve_id"],
        "vulnerability": {
            "cve_id": case["cve_id"],
            "vendor": outcome.get("vendor") or reading.get("vendor"),
            "product": outcome.get("product") or reading.get("product"),
            "description": nvd.get("description"),
            "cvss3_score": nvd.get("cvss3_score"),
            "cwe_ids": nvd.get("cwe_ids"),
            "kev_added": outcome.get("kev_added"),
            "days_published_to_kev": outcome.get("days_published_to_kev"),
            "context_note": nvd.get("warning"),
        },
        "ranking": {
            "outcome": case["classification"],
            "ensemble_rank": r["ensemble_rank"],
            "review_cutoff": r["review_cutoff"],
            "places_outside_cutoff": r["places_outside_cutoff"],
            "miss_band": r.get("miss_band"),
            "model_ranks": [{"model": DISPLAY_VOTERS[k], "rank": v, "inside_own_top_517": v <= r["review_cutoff"]}
                            for k, v in voters.items()],
            "best_model": DISPLAY_VOTERS[best],
        },
        "verified_evidence": {
            "summary": vf["q1_what_happened"],
            "snapshot_signals": vf["q2_observed_contributors"]["snapshot_signals"],
            "information_gaps": vf["q2_observed_contributors"]["information_gaps"],
            "model_disagreement": vf["q2_observed_contributors"]["model_disagreement"]["fact"],
            "linear_model_factors": {
                "attribution_reliable": attribution["attribution_reliable_for_this_cve"],
                "holding_it_back": [{"feature": d["meaning"], "this_cve": d["this_cve_value"],
                                     "typical_top_517": d["typical_top_517_value"]}
                                    for d in attribution["features_holding_it_back"]],
                "in_its_favour": [{"feature": d["meaning"], "this_cve": d["this_cve_value"],
                                   "typical_top_517": d["typical_top_517_value"]}
                                  for d in attribution["features_in_its_favor"]],
            },
            "granite_description_reading": reading,
            "peer_context": vf["q3_context_for_lessons"]["peer_context"],
        },
        "ai_analysis": {
            "summary": ai["what_happened"],
            "possible_explanations": explanations(ai, labels),
            "analyst_takeaways": takeaways(ai, labels),
            "limitations": ai["caveats"],
            "label": "AI-written hypotheses and lessons, checked against the evidence. Not verified causes.",
        },
    }


def cohort_item(record: dict, labels: dict[str, str]) -> dict:
    ai, vf = record["ai_generated"], record["verified_findings"]
    return {
        "id": "cohort",
        "record_key": "cohort",
        "verified_evidence": {
            "miss_bands": vf["miss_bands"],
            "features_separating_missed_from_caught": vf["features_separating_missed_from_caught"],
            "information_gap_counts_among_43_misses": vf["information_gap_counts_among_43_misses"],
            "model_disagreement_test": vf["blind_spot_findings"],
        },
        "ai_analysis": {
            "summary": ai["what_happened"],
            "possible_explanations": explanations(ai, labels),
            "analyst_takeaways": takeaways(ai, labels),
            "limitations": ai["caveats"],
            "label": "AI-written hypotheses and lessons, checked against the evidence. Not verified causes.",
        },
    }


def main() -> int:
    evidence = w.load_evidence()
    cases = {c["cve_id"]: c for c in evidence["cases"]}
    source_payload = json.loads(w.RESULT_PATH.read_text(encoding="utf-8"))
    records = source_payload["investigations"]

    not_passed = [k for k, v in records.items() if v["ai_generated"]["status"] != "passed_checks"]
    if not_passed:
        raise ValueError(f"Run --recheck and resolve these first; not passed_checks: {not_passed}")

    cohort, items, provenance = None, [], {}
    for key, record in records.items():
        ai = record["ai_generated"]
        source = ai.get("source", "ibm_watsonx_ai")
        provenance[key] = {"source": source, "source_label": SOURCE_LABELS[source], "model_id": ai["model_id"],
                           "validation_status": ai["status"], "record_sha256": record_hash(record),
                           "revised_from_watsonx_draft": "watsonx_original" in ai}
        if record["kind"] == "cohort":
            cohort = cohort_item(record, w.cohort_packet(evidence)["allowed_evidence_anchors"])
            continue
        case = cases[key]
        verified_ranks = record["verified_findings"]["q2_observed_contributors"]["model_disagreement"]
        if case["ranking"]["voter_ranks"][verified_ranks["best_model"]] != verified_ranks["best_rank"]:
            raise ValueError(f"{key}: evidence ranks disagree with the validated record")
        items.append(case_item(record, case, w.anchors_for_case(case)))
    items.sort(key=lambda x: x["ranking"]["ensemble_rank"])

    payload = {
        "meta": {
            "title": "Blind Spot Investigator: historical KEV misses",
            "built_at_utc": datetime.now(timezone.utc).isoformat(),
            "scope": ("Chen's final ensemble ranked 75,148 CVEs published 2024-2025; analysts review the top 517. "
                      "75 were later added to CISA KEV: 32 inside the top 517 (caught), 43 outside (missed)."),
            "total_cves": 75148, "review_cutoff": 517, "kev_positives": 75, "caught": 32, "missed": 43,
            "how_to_read": ("verified_evidence is computed from historical data. ai_analysis contains hypotheses and "
                            "analyst takeaways tied to that evidence; they are not verified causes and do not "
                            "predict 2026 exploitation. Missing exploit-signal data means unknown, not absent."),
            "source_records": {"file": w.RESULT_PATH.name, "sha256": hashlib.sha256(
                w.RESULT_PATH.read_bytes()).hexdigest(), "lookup": "investigations[record_key]"},
        },
        "cohort": cohort,
        "caught_context": sorted(
            ({"cve_id": c["cve_id"], "ensemble_rank": c["ranking"]["ensemble_rank"],
              "vendor": c["outcome_not_a_model_input"].get("vendor"),
              "product": c["outcome_not_a_model_input"].get("product")}
             for c in evidence["cases"] if c["classification"] == "caught"),
            key=lambda x: x["ensemble_rank"]),
        "investigations": items,
        "provenance": provenance,
    }
    DASHBOARD_PATH.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {len(items)} investigations + cohort to {DASHBOARD_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
